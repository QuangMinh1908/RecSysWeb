-- pg_trgm giúp ILIKE '%keyword%' chạy nhanh khi bảng có hàng trăm nghìn dòng
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ---------- products: ánh xạ dữ liệu cào từ Shopee ----------
CREATE TABLE IF NOT EXISTS products (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(500)  NOT NULL,
    price          NUMERIC(15,2) NOT NULL CHECK (price >= 0),
    original_price NUMERIC(15,2),
    image_url      TEXT,
    description    TEXT
);

CREATE INDEX IF NOT EXISTS idx_products_name_trgm
    ON products USING gin (name gin_trgm_ops);

-- ---------- users: phục vụ đăng nhập ----------
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(100),
    created_at    TIMESTAMP    NOT NULL DEFAULT now()
);

-- ---------- user_interactions: log hành vi (click, cart, buy) ----------
CREATE TABLE IF NOT EXISTS user_interactions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT      NOT NULL REFERENCES users(id)    ON DELETE CASCADE,
    product_id       BIGINT      NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    interaction_type VARCHAR(20) NOT NULL CHECK (interaction_type IN ('CLICK', 'CART', 'BUY')),
    created_at       TIMESTAMP   NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_interactions_user    ON user_interactions (user_id);
CREATE INDEX IF NOT EXISTS idx_interactions_product ON user_interactions (product_id);
